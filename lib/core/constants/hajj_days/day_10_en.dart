During Ihram, refraining for an extended period from cutting hair or nails, using perfume, and ordinary grooming creates a state of physical untidiness — this is what is meant by "Tafath." Halq or Qasr removes this untidiness.

**To achieve complete cleanliness, it is best to carry out the following acts in this period, according to the Sunnah—**

- Shaving the head or trimming the hair
- Cutting the nails of the hands and feet
- Trimming the mustache
- Removing unwanted underarm and pubic hair
- Taking a complete bath (ghusl) to cleanse the body
- Wearing new or clean clothing, if possible

This cleanliness is significant not only physically but also spiritually. After the difficult, restrained period of Ihram, achieving this cleanliness marks a symbolic return to purity and ordinary life for the pilgrim.

