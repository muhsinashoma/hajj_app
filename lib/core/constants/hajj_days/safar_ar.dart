١٩. عَنْ صَلَاةِ الْمُسَافِر: رُوِيَ عَنْ يَعْلَى بْنِ أُمَيَّةَ رَضِيَ اللَّهُ عَنْهُ أَنَّهُ قَال: قُلْتُ لِعُمَرَ رَضِيَ اللَّهُ عَنْه: يَقُولُ اللَّهُ تَعَالَى: «فَلَيْسَ عَلَيْكُمْ جُنَاحٌ أَنْ تَقْصُرُوا مِنَ الصَّلَاةِ إِنْ خِفْتُمْ أَنْ يَفْتِنَكُمُ الَّذِينَ كَفَرُوا إِنَّ الْكَافِرِينَ كَانُوا لَكُمْ عَدُوًّا مُبِينًا» (سُورَةُ النِّسَاء: ٤:١٠١)—فَقَدْ أَمِنَ النَّاسُ الْآن، فَمَا بَالُ الْقَصْر؟ فَقَالَ عُمَرُ رَضِيَ اللَّهُ عَنْه: «عَجِبْتُ مِمَّا عَجِبْتَ مِنْه، فَسَأَلْتُ رَسُولَ اللَّهِ ﷺ عَنْ ذَلِك، فَقَال: صَدَقَةٌ تَصَدَّقَ اللَّهُ بِهَا عَلَيْكُم، فَاقْبَلُوا صَدَقَتَه.»

(صَحِيحُ مُسْلِم: ٦٨٦؛ سُنَنُ أَبِي دَاوُد: ١١٩٩؛ سُنَنُ التِّرْمِذِيّ: ٣٠٣٦)

رُوِيَ عَنِ ابْنِ عَبَّاسٍ رَضِيَ اللَّهُ عَنْهُمَا أَنَّ رَسُولَ اللَّهِ ﷺ أَقَامَ فِي سَفَرٍ تِسْعَةَ عَشَرَ يَوْمًا يَقْصُرُ الصَّلَاة.

(صَحِيحُ الْبُخَارِيّ: ١٠٨٠؛ سُنَنُ أَبِي دَاوُد: ١٢٥٠؛ سُنَنُ التِّرْمِذِيّ: ٥٤٩؛ سُنَنُ ابْنِ مَاجَه: ١٠٧٠)

رُوِيَ عَنْ أَنَسٍ رَضِيَ اللَّهُ عَنْهُ أَنَّهُ قَال: خَرَجْنَا مَعَ النَّبِيِّ ﷺ مِنَ الْمَدِينَةِ إِلَى مَكَّةَ فَكَانَ يُصَلِّي رَكْعَتَيْنِ حَتَّى رَجَعْنَا. قِيلَ لِأَنَسٍ رَضِيَ اللَّهُ عَنْه: كَمْ أَقَمْتُمْ بِمَكَّة؟ قَال: أَقَمْنَا بِهَا عَشْرًا.

(صَحِيحُ الْبُخَارِيّ: ١٠٨١؛ صَحِيحُ مُسْلِم: ٦٩٣)

**الْجَمْعُ بَيْنَ الصَّلَاتَيْنِ فِي السَّفَر:**

رُوِيَ عَنْ عَبْدِ اللَّهِ بْنِ عُمَرَ رَضِيَ اللَّهُ عَنْهُمَا أَنَّهُ قَال: رَأَيْتُ رَسُولَ اللَّهِ ﷺ إِذَا عَجَّلَ بِهِ السَّيْرُ فِي السَّفَر، أَخَّرَ الْمَغْرِبَ ثُمَّ جَمَعَ بَيْنَهَا وَبَيْنَ الْعِشَاء.

